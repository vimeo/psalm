<?php

declare(strict_types=1);

// Generates src/Psalm/StrId.php, containing precomputed ids of interned strings.
//
// Every `StrId::<name>` reference found in src/, tests/ and examples/ produces a constant
// with the id of the string 'Foo' (and its lowercase version is preloaded as well).
// Strings which are not valid identifiers (e.g. namespaced class names) are listed in
// bin/str_ids.php as a map of constant name => string.

$root = dirname(__DIR__);

/** @var array<string, string> */
$explicit = require __DIR__ . '/str_ids.php';

$reserved = ['STRINGS' => true, 'IDS' => true, 'LOWER' => true, 'class' => true];

$constants = $explicit;

foreach (['src', 'tests', 'examples', 'bin'] as $dir) {
    $it = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($root . '/' . $dir));
    foreach ($it as $file) {
        if (!$file->isFile() || $file->getExtension() !== 'php') {
            continue;
        }
        $contents = file_get_contents($file->getPathname());
        if (!preg_match_all('/\bStrId::([A-Za-z_][A-Za-z0-9_]*)\b/', $contents, $matches)) {
            continue;
        }
        foreach ($matches[1] as $name) {
            if (isset($reserved[$name]) || isset($constants[$name])) {
                continue;
            }
            $constants[$name] = $name;
        }
    }
}

ksort($constants, SORT_STRING);

$hash = static fn(string $str): int => unpack('J', hash('xxh3', $str, true))[1];

$fmt = static fn(int $id): string => $id === PHP_INT_MIN ? 'PHP_INT_MIN' : (string) $id;

$strings = [];
foreach ($constants as $value) {
    $strings[$value] = $hash($value);
    $lower = strtolower($value);
    $strings[$lower] = $hash($lower);
}
ksort($strings, SORT_STRING);

$ids = [];
foreach ($strings as $str => $id) {
    if (isset($ids[$id])) {
        throw new RuntimeException("Hash collision between {$ids[$id]} and $str");
    }
    $ids[$id] = $str;
}

$out = "<?php\n\n// This file is generated by bin/generate_str_ids.php, do not edit it manually.\n"
    . "// phpcs:ignoreFile\n\n"
    . "declare(strict_types=1);\n\nnamespace Psalm;\n\n"
    . "/**\n * Precomputed ids of commonly used interned strings, see {@see Interner}.\n *\n"
    . " * @api\n * @psalm-immutable\n */\n"
    . "final class StrId\n{\n";

foreach ($constants as $name => $value) {
    $out .= '    public const ' . $name . ' = ' . $fmt($hash($value)) . ";\n";
}

$out .= "\n    /** @internal */\n    public const STRINGS = [\n";
foreach ($strings as $str => $id) {
    $out .= '        ' . $fmt($id) . ' => ' . var_export((string) $str, true) . ",\n";
}
$out .= "    ];\n\n    /** @internal */\n    public const IDS = [\n";
foreach ($strings as $str => $id) {
    $out .= '        ' . var_export((string) $str, true) . ' => ' . $fmt($id) . ",\n";
}
$out .= "    ];\n\n    /** @internal */\n    public const LOWER = [\n";
foreach ($strings as $str => $id) {
    $out .= '        ' . $fmt($id) . ' => ' . $fmt($strings[strtolower((string) $str)]) . ",\n";
}
$out .= "    ];\n}\n";

file_put_contents($root . '/src/Psalm/StrId.php', $out);
